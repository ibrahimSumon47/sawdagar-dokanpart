#!/usr/bin/env node
/**
 * Compiles the CS core native modules to WebAssembly with clang and embeds them
 * as base64 TypeScript modules, so Next.js and Node can instantiate them without
 * file system tracing or bundler configuration.
 *
 * Requires clang with the wasm32 target and wasm-ld, which ship with LLVM on
 * Linux, macOS and Windows. The compiled artifacts are committed, so a normal
 * install, test or deploy never needs clang:
 *
 *   pnpm cs:build-wasm
 */

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageDir = path.join(root, 'packages', 'cs-core');
const generatedDir = path.join(packageDir, 'generated');

/** Native module name, source, exported symbols and generated TypeScript file. */
const modules = [
  {
    name: 'search-core',
    source: 'native/search_core.cpp',
    language: 'c++',
    exports: ['alloc', 'reset', 'rank'],
    output: 'searchCoreWasm.ts',
    exportName: 'searchCoreWasmBase64',
  },
  {
    name: 'sku-kit',
    source: 'native/sku_kit.c',
    language: 'c',
    exports: ['alloc', 'reset', 'sku_normalize', 'sku_valid', 'sku_check'],
    output: 'skuKitWasm.ts',
    exportName: 'skuKitWasmBase64',
  },
];

function findClang() {
  const candidates = [
    process.env.CLANG_PATH,
    'clang',
    process.platform === 'win32'
      ? path.join(process.env.ProgramFiles ?? 'C:\\Program Files', 'LLVM', 'bin', 'clang.exe')
      : undefined,
    '/usr/bin/clang',
    '/opt/homebrew/opt/llvm/bin/clang',
  ].filter((candidate) => typeof candidate === 'string' && candidate.length > 0);

  for (const candidate of candidates) {
    if (candidate.includes(path.sep) && !existsSync(candidate)) continue;
    const result = spawnSync(candidate, ['--version'], { encoding: 'utf8' });
    if (result.status === 0) return candidate;
  }

  console.error('clang was not found. Set CLANG_PATH or install LLVM.');
  process.exit(1);
}

const clang = findClang();
mkdirSync(generatedDir, { recursive: true });
const scratchDir = mkdtempSync(path.join(tmpdir(), 'sd-cs-core-'));

for (const item of modules) {
  const source = path.join(packageDir, item.source);
  const binary = path.join(scratchDir, `${item.name}.wasm`);
  const result = spawnSync(
    clang,
    [
      '--target=wasm32',
      '-Oz',
      '-nostdlib',
      ...(item.language === 'c++' ? ['-fno-exceptions', '-fno-rtti'] : []),
      '-Wl,--no-entry',
      ...item.exports.map((symbol) => `-Wl,--export=${symbol}`),
      '-o',
      binary,
      source,
    ],
    { encoding: 'utf8' },
  );

  if (result.status !== 0) {
    console.error(`Compiling ${item.name} failed.\n${result.stderr ?? ''}`);
    process.exit(1);
  }

  const bytes = readFileSync(binary);
  writeFileSync(
    path.join(generatedDir, item.output),
    `// Generated by scripts/build-wasm.mjs from ${item.source}. Do not edit.\nexport const ${item.exportName} =\n  '${bytes.toString('base64')}';\n`,
  );
  console.log(`${item.name}: ${bytes.length} bytes`);
}

rmSync(scratchDir, { recursive: true, force: true });
console.log(`Wrote base64 modules to ${path.relative(root, generatedDir)}.`);
