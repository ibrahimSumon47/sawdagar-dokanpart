#!/usr/bin/env node
/**
 * One-off maintenance script: downloads one openly licensed photograph per top
 * department from Wikimedia Commons into apps/web/public/media/departments and
 * writes the attribution file used by /credits.
 *
 * Run only when deliberately replacing the catalog photography:
 *   node scripts/fetch-catalog-media.mjs
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = path.join(root, 'apps', 'web', 'public', 'media', 'departments');
const userAgent = 'SawdagarDokanpatDemo/1.0 (portfolio project; ibrahimsumon005@gmail.com)';
const requireWeb = createRequire(path.join(root, 'apps', 'web', 'package.json'));
const sharp = requireWeb('sharp');

/** Department slug, chosen Commons file (or search term) and credit label. */
const departments = [
  { slug: 'sarees', title: 'Dhaka Sari Fabric 1.jpg', label: 'Saree' },
  { slug: 'panjabi', title: 'Button of Panjabi 1.jpg', label: 'Panjabi' },
  { slug: 'handloom', title: 'BN-weaver.jpg', label: 'Handloom weaving' },
  { slug: 'nakshi-kantha', title: 'Embroidered Quilt (নকশি কাঁথা).jpg', label: 'Nakshi kantha' },
  { slug: 'jute', title: 'Jute Bag.JPG', label: 'Jute goods' },
  { slug: 'cane-bamboo', title: 'A bamboo basket image 1.JPG', label: 'Cane and bamboo' },
  { slug: 'pottery', title: 'The story of clay pottery 2.jpg', label: 'Pottery' },
  { slug: 'brassware', title: 'Brass pot.jpg', label: 'Brassware' },
  { slug: 'leather', title: 'An old wallet with brown color.jpg', label: 'Leather goods' },
  { slug: 'home-kitchen', title: 'Clay pot workshop 20220916120232.jpg', label: 'Kitchenware' },
  { slug: 'beauty-care', title: 'Handmade soap.jpg', label: 'Beauty and care' },
  { slug: 'books-stationery', title: 'Old Books 01.JPG', label: 'Books and stationery' },
];

const allowedLicense = /^(CC0|Public domain|CC BY(-SA)? \d\.\d|CC BY(-SA)?)$/i;

async function lookup(department) {
  const url = new URL('https://commons.wikimedia.org/w/api.php');
  if (department.title) {
    url.search = new URLSearchParams({
      action: 'query',
      titles: `File:${department.title}`,
      prop: 'imageinfo',
      iiprop: 'url|extmetadata',
      iiurlwidth: '960',
      format: 'json',
    }).toString();
  } else {
    url.search = new URLSearchParams({
      action: 'query',
      generator: 'search',
      gsrsearch: `filetype:bitmap ${department.term}`,
      gsrlimit: '8',
      gsrnamespace: '6',
      prop: 'imageinfo',
      iiprop: 'url|extmetadata',
      iiurlwidth: '960',
      format: 'json',
    }).toString();
  }

  const response = await fetch(url, { headers: { 'User-Agent': userAgent } });
  if (!response.ok) throw new Error(`Commons lookup failed for ${department.slug}: ${response.status}`);
  const body = await response.json();
  return Object.values(body.query?.pages ?? {});
}

async function download(department) {
  for (const page of await lookup(department)) {
    const info = page.imageinfo?.[0];
    const license = info?.extmetadata?.LicenseShortName?.value ?? '';
    if (!info?.thumburl || !allowedLicense.test(license)) continue;

    const image = await fetch(info.thumburl.split('?')[0], { headers: { 'User-Agent': userAgent } });
    if (!image.ok) continue;
    const buffer = Buffer.from(await image.arrayBuffer());
    if (buffer.length < 20_000 || buffer.length > 900_000) continue;

    const resized = await sharp(buffer)
      .resize(800, 600, { fit: 'cover', position: 'centre' })
      .jpeg({ quality: 74, progressive: true, mozjpeg: true })
      .toBuffer();

    return {
      buffer: resized,
      title: page.title.replace(/^File:/, ''),
      license,
      author: (info.extmetadata?.Artist?.value ?? 'Unknown')
        .replace(/<[^>]+>/g, '')
        .trim(),
      source: info.descriptionurl,
    };
  }
  return null;
}

mkdirSync(outputDir, { recursive: true });
const credits = [];

for (const department of departments) {
  const found = await download(department);
  if (!found) {
    console.warn(`${department.slug}: no suitably licensed image found`);
    continue;
  }
  writeFileSync(path.join(outputDir, `${department.slug}.jpg`), found.buffer);
  credits.push({
    slug: department.slug,
    label: department.label,
    file: `/media/departments/${department.slug}.jpg`,
    title: found.title,
    author: found.author,
    license: found.license,
    source: found.source,
  });
  console.log(`${department.slug}: ${found.title} (${found.license}, ${Math.round(found.buffer.length / 1024)} KB)`);
}

writeFileSync(
  path.join(root, 'apps', 'web', 'features', 'catalog', 'mediaCredits.ts'),
  `/** Generated by scripts/fetch-catalog-media.mjs. Photograph credits for department media. */\nexport interface MediaCredit {\n  slug: string;\n  label: string;\n  file: string;\n  title: string;\n  author: string;\n  license: string;\n  source: string;\n}\n\nexport const mediaCredits: MediaCredit[] = ${JSON.stringify(credits, null, 2)};\n`,
);
console.log(`Wrote ${credits.length} credits.`);
